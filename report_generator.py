
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)
from reportlab.lib.colors import HexColor
from io import BytesIO


def generate_pdf_report(
    filename,
    detected_objects,
    scene_description,
    extracted_text
):

    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=45,
        leftMargin=45,
        topMargin=45,
        bottomMargin=45
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "CustomTitle",
        parent=styles["Title"],
        fontSize=25,
        textColor=HexColor("#8B5CF6"),
        alignment=TA_CENTER,
        spaceAfter=10
    )

    heading_style = ParagraphStyle(
        "CustomHeading",
        parent=styles["Heading2"],
        textColor=HexColor("#8B5CF6"),
        spaceBefore=15,
        spaceAfter=8
    )

    body_style = styles["BodyText"]

    elements = []

    # TITLE
    elements.append(
        Paragraph("SceneSense AI", title_style)
    )

    elements.append(
        Paragraph(
            "Visual Understanding Analysis Report",
            styles["Heading3"]
        )
    )

    elements.append(Spacer(1, 20))

    # IMAGE INFORMATION
    elements.append(
        Paragraph("Image Information", heading_style)
    )

    elements.append(
        Paragraph(f"<b>Filename:</b> {filename}", body_style)
    )

    elements.append(Spacer(1, 15))

    # SCENE DESCRIPTION
    elements.append(
        Paragraph("AI Scene Description", heading_style)
    )

    elements.append(
        Paragraph(scene_description or "No description available.", body_style)
    )

    elements.append(Spacer(1, 15))

    # OBJECT DETECTION
    elements.append(
        Paragraph("Detected Objects", heading_style)
    )

    if detected_objects:

        table_data = [
            ["Object", "Confidence"]
        ]

        for obj in detected_objects:

            table_data.append([
                obj["name"].title(),
                f'{obj["confidence"]}%'
            ])

        object_table = Table(
            table_data,
            colWidths=[3.5 * inch, 2 * inch]
        )

        object_table.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), HexColor("#8B5CF6")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("PADDING", (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [
                    colors.white,
                    HexColor("#F3F0FF")
                ])
            ])
        )

        elements.append(object_table)

    else:

        elements.append(
            Paragraph("No objects detected.", body_style)
        )

    elements.append(Spacer(1, 15))

    # OCR TEXT
    elements.append(
        Paragraph("Extracted Text (OCR)", heading_style)
    )

    if extracted_text:

        for item in extracted_text:

            elements.append(
                Paragraph(
                    f'• {item["text"]} '
                    f'({item["confidence"]}% confidence)',
                    body_style
                )
            )

            elements.append(Spacer(1, 5))

    else:

        elements.append(
            Paragraph("No readable text found.", body_style)
        )

    elements.append(Spacer(1, 30))

    # FOOTER
    elements.append(
        Paragraph(
            "Generated by SceneSense AI | "
            "YOLOv8 • BLIP • EasyOCR • OpenCV",
            styles["Italic"]
        )
    )

    document.build(elements)

    buffer.seek(0)

    return buffer.getvalue()
